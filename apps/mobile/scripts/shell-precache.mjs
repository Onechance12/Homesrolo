import { createHash } from 'node:crypto'
import { readFile, stat } from 'node:fs/promises'
import path from 'node:path'

export const MAX_GENERATED_SHELL_DEPENDENCIES = 128
export const MAX_HOSTED_SHELL_ASSETS = 160
export const FIXED_HOSTED_SHELL_ASSETS = Object.freeze([
  '/apple-icon.png',
  '/expo-shell-assets.js',
  '/expo-shell.html',
  '/icon.svg',
  '/icon-192.png',
  '/icon-512.png',
  '/icon-maskable-512.png',
  '/manifest.webmanifest',
  '/register-sw.js',
])

const GENERATED_PREFIXES = ['/_expo/static/', '/assets/']
const FIXED_HOSTED_SHELL_ASSET_SET = new Set(FIXED_HOSTED_SHELL_ASSETS)
const TEXT_DEPENDENCY_EXTENSIONS = new Set(['.css', '.html', '.js', '.json', '.mjs'])
const GENERATED_ASSET_URL = /(?:\/_expo\/static\/|\/assets\/)[^"'`\\\s<>()]+/g

function isGeneratedAssetPath(assetPath) {
  return GENERATED_PREFIXES.some(prefix => assetPath.startsWith(prefix))
}

function normalizeGeneratedAssetPath(candidate) {
  const url = new URL(candidate, 'https://app.homesrolo.com')
  if (url.origin !== 'https://app.homesrolo.com' || !isGeneratedAssetPath(url.pathname)) {
    throw new Error(`Unsafe generated shell dependency: ${candidate}`)
  }
  return url.pathname
}

export function extractGeneratedAssetPaths(source) {
  return [...new Set(
    [...source.matchAll(GENERATED_ASSET_URL)]
      .map(match => normalizeGeneratedAssetPath(match[0])),
  )].sort()
}

function generatedFilePath(exportDirectory, assetPath) {
  const exportRoot = path.resolve(exportDirectory)
  const filePath = path.resolve(exportRoot, `.${assetPath}`)
  if (filePath !== exportRoot && !filePath.startsWith(`${exportRoot}${path.sep}`)) {
    throw new Error(`Generated shell dependency escapes the export: ${assetPath}`)
  }
  return filePath
}

export async function collectGeneratedShellDependencies({ exportDirectory, sourceShell }) {
  const dependencies = new Set()
  const queue = extractGeneratedAssetPaths(sourceShell)

  while (queue.length > 0) {
    const assetPath = queue.shift()
    if (!assetPath || dependencies.has(assetPath)) continue
    if (dependencies.size >= MAX_GENERATED_SHELL_DEPENDENCIES) {
      throw new Error(
        `Expo shell exceeds the ${MAX_GENERATED_SHELL_DEPENDENCIES}-asset offline limit.`,
      )
    }

    const filePath = generatedFilePath(exportDirectory, assetPath)
    const details = await stat(filePath).catch(() => null)
    if (!details?.isFile()) {
      throw new Error(`Expo shell dependency is missing from the export: ${assetPath}`)
    }
    dependencies.add(assetPath)

    if (!TEXT_DEPENDENCY_EXTENSIONS.has(path.extname(filePath).toLowerCase())) continue
    const source = await readFile(filePath, 'utf8')
    for (const nestedPath of extractGeneratedAssetPaths(source)) {
      if (!dependencies.has(nestedPath)) queue.push(nestedPath)
    }
    queue.sort()
  }

  return [...dependencies].sort()
}

export function createShellRevision(entries) {
  const hash = createHash('sha256')
  for (const entry of [...entries].sort((left, right) => left.url.localeCompare(right.url))) {
    const content = Buffer.isBuffer(entry.content) ? entry.content : Buffer.from(entry.content)
    hash.update(entry.url)
    hash.update('\0')
    hash.update(content)
    hash.update('\0')
  }
  return hash.digest('hex').slice(0, 20)
}

export function renderShellPrecacheManifest({ assets, revision }) {
  const exactAssets = [...new Set(assets)].sort()
  if (exactAssets.length === 0 || exactAssets.length > MAX_HOSTED_SHELL_ASSETS) {
    throw new Error('Hosted shell precache manifest has an invalid asset count.')
  }
  if (!/^[a-f0-9]{20}$/.test(revision)) {
    throw new Error('Hosted shell precache revision must be a 20-character SHA-256 prefix.')
  }
  for (const assetPath of exactAssets) {
    if ((!FIXED_HOSTED_SHELL_ASSET_SET.has(assetPath) && !isGeneratedAssetPath(assetPath))
      || assetPath.startsWith('//')
      || assetPath.includes('..')) {
      throw new Error(`Hosted shell precache path is unsafe: ${assetPath}`)
    }
  }

  const manifest = JSON.stringify({
    cacheName: `homesrolo-shell-${revision}`,
    assets: exactAssets,
  }, null, 2)
  return `/* Generated by export-web-for-homeowner.mjs. Do not edit. */\nself.HOMESROLO_SHELL_MANIFEST = Object.freeze(${manifest})\n`
}
